package ec.edu.ups.modelo;

/**
 * Enumeración que representa los tipos de preguntas de seguridad.
 *
 * @author JuanOrtiz2006
 * @version 1.0
 */
public enum TipoPregunta {
    /**
     * Pregunta de tipo personal.
     */
    PERSONAL,
    /**
     * Pregunta de tipo familiar.
     */
    FAMILIAR,
    /**
     * Pregunta de tipo histórica.
     */
    HISTORICA,
    /**
     * Pregunta relacionada al trabajo.
     */
    TRABAJO,
    /**
     * Pregunta sobre un lugar.
     */
    LUGAR
}
